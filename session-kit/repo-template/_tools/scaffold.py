#!/usr/bin/env python
"""
scaffold.py — deterministically create a play group's folder structure and stubs.

Builds groups/<group>/{players, world/{people,places,things}, sessions} with .gitkeep
files and the three world stubs (events.md, threads.md, relationships.md), all in the
exact format the existing groups use. Idempotent: only creates what's missing, never
overwrites a populated file.

Usage:
  python scaffold.py --group winterfell
  python scaffold.py --group winterfell --title "Winterfell Falls"

Pure stdlib.
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stonetop_lib as lib

KEEP_DIRS = ["players", "world/people", "world/places", "world/things", "sessions"]


def title_for(group, override):
    if override:
        return override
    cfg = os.path.join(lib.REPO, "config.json")
    if os.path.exists(cfg):
        try:
            with open(cfg, encoding="utf-8") as f:
                data = json.load(f)
            t = data.get("groups", {}).get(group, {}).get("title")
            if t:
                return t
        except Exception:
            pass
    return group


def events_stub(title):
    return (f"# World Events — {title}\n\n"
            "A running log of what has changed in Stonetop and the wider world, newest at "
            "the top.\nMaintained by `/retriever-recap`.\n\n"
            "<!-- - **Session NN:** <what changed> -->\n")


def threads_stub(title):
    return (f"# Open Threads — {title}\n\n"
            "Questions and dangers left hanging, to pull on in future sessions. Maintained "
            "by\n`/retriever-recap`.\n\n"
            "<!-- - [ ] <an open question or looming danger> (since session NN) -->\n")


def rel_stub(title, group):
    return (f"# Relationship Map — {title}\n\n"
            "<!-- GENERATED by /retriever-graph (_tools/build_graph.py). Do not edit by "
            "hand;\n     edit the `## Relationships` blocks on the entity notes instead, "
            "then regenerate. -->\n\n"
            f"Run `/retriever-graph {group}` to generate the map from the entity notes.\n")


def main():
    ap = argparse.ArgumentParser(description="Scaffold a Stonetop play group.")
    ap.add_argument("--group", required=True)
    ap.add_argument("--title", default="", help="display title (else config.json or name)")
    args = ap.parse_args()

    base = lib.group_dir(args.group)
    title = title_for(args.group, args.title)
    created = []

    for d in KEEP_DIRS:
        full = os.path.join(base, d)
        os.makedirs(full, exist_ok=True)
        keep = os.path.join(full, ".gitkeep")
        if not os.path.exists(keep):
            open(keep, "w").close()

    world = os.path.join(base, "world")
    for fn, text in [("events.md", events_stub(title)),
                     ("threads.md", threads_stub(title)),
                     ("relationships.md", rel_stub(title, args.group))]:
        path = os.path.join(world, fn)
        if lib.write_new(path, text):
            created.append(os.path.relpath(path, lib.REPO))

    print(f"Scaffolded group '{args.group}' ({title}).")
    if created:
        print("Created:\n  " + "\n  ".join(created))
    else:
        print("All world stubs already present.")
    print("Next: copy config.example.json to config.json and add this group's title, "
          "discord_webhook, and roster.")


if __name__ == "__main__":
    main()
